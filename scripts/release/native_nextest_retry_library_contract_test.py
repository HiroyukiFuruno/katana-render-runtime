from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import subprocess
import tempfile
import unittest
import uuid
from pathlib import Path
from typing import cast

import native_nextest_coverage_commands as coverage_commands
import native_nextest_retry_artifacts as retry_artifacts
import native_nextest_root_coverage as root_coverage


REPO = Path(__file__).resolve().parents[2]
RUN_ID_RE = re.compile(
    r"Nextest run ID ([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})"
)
FIXTURE_MANIFEST = """\
[package]
name = "native-nextest-retry-fixture"
version = "0.1.0"
edition = "2021"

[workspace]

[profile.krr-coverage]
inherits = "dev"
debug = 0
incremental = false
"""
FIXTURE_LOCK = """\
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "native-nextest-retry-fixture"
version = "0.1.0"
"""
FIXTURE_SOURCE = r'''
#[cfg(test)]
mod tests {
    use std::{env, fs, path::PathBuf};

    fn increment(name: &str) {
        let path = PathBuf::from(env::var_os("RETRY_FIXTURE_STATE").unwrap()).join(name);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        let current = fs::read_to_string(&path)
            .ok()
            .and_then(|value| value.parse::<u32>().ok())
            .unwrap_or(0);
        fs::write(path, (current + 1).to_string()).unwrap();
    }

    #[inline(never)]
    fn covered_only_by_passed_case() -> usize {
        let passed_only_value = 37;
        passed_only_value + 5
    }

    #[test]
    fn passed_case_runs_once() {
        increment("passed-count");
        assert_eq!(covered_only_by_passed_case(), 42);
    }

    #[test]
    fn failed_case_runs_again() {
        increment("failed-count");
        let marker = PathBuf::from(env::var_os("RETRY_FIXTURE_STATE").unwrap())
            .join("first-attempt-complete");
        if marker.exists() {
            return;
        }
        fs::write(marker, b"first attempt").unwrap();
        panic!("intentional first-attempt failure");
    }
}
'''


class NativeNextestRetryLibraryContractTests(unittest.TestCase):
    def setUp(self) -> None:
        evidence_parent = REPO / "tmp/quality/native-nextest-library-contract"
        evidence_parent.mkdir(parents=True, exist_ok=True)
        self.evidence = evidence_parent / str(uuid.uuid4())
        self.evidence.mkdir()
        print(f"Nextest library contract evidence: {self.evidence}")
        self.temporary = tempfile.TemporaryDirectory(prefix="krr-nextest-retry-library-")
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name).resolve()
        self.state = self.root / "fixture-state"
        self.target = self.root / "target"
        self.cov_target = self.target / "llvm-cov-target"
        self.nextest_state = self.target / "nextest-root-state"
        self._write_fixture()

    def _write_fixture(self) -> None:
        (self.root / "src").mkdir()
        (self.root / "Cargo.toml").write_text(FIXTURE_MANIFEST, encoding="utf-8")
        (self.root / "Cargo.lock").write_text(FIXTURE_LOCK, encoding="utf-8")
        (self.root / "src/lib.rs").write_text(FIXTURE_SOURCE, encoding="utf-8")

    def _environment(self, attempt: str) -> dict[str, str]:
        environment = dict(os.environ)
        environment.pop("LLVM_PROFILE_FILE", None)
        environment["CARGO_TARGET_DIR"] = str(self.target)
        environment["CARGO_LLVM_COV_TARGET_DIR"] = str(self.cov_target)
        environment["NEXTEST_STATE_DIR"] = str(self.nextest_state)
        environment["LLVM_PROFILE_FILE_NAME"] = f"retry-{attempt}-%4m.profraw"
        environment["RETRY_FIXTURE_STATE"] = str(self.state)
        return environment

    def _run(self, arguments: list[str], attempt: str) -> subprocess.CompletedProcess[str]:
        return self._execute(arguments, attempt, self.root, self._environment(attempt))

    def _execute(
        self, arguments: list[str], stage: str, cwd: Path, environment: dict[str, str],
    ) -> subprocess.CompletedProcess[str]:
        cargo = shutil.which("cargo")
        if cargo is None:
            self.fail("cargo executable is required")
        argv = [cargo, *arguments]
        code = root_coverage._execute(self.evidence, stage, argv, cwd, environment)
        return self._completed_process(self.evidence / stage, argv, code)

    def _completed_process(
        self, logs: Path, argv: list[str], code: int,
    ) -> subprocess.CompletedProcess[str]:
        stdout = (logs / "stdout.raw").read_text(encoding="utf-8", errors="replace")
        stderr = (logs / "stderr.raw").read_text(encoding="utf-8", errors="replace")
        return subprocess.CompletedProcess(argv, code, stdout, stderr)

    def _nextest_arguments(self, parent: str | None) -> list[str]:
        return [
            *coverage_commands.nextest_arguments(REPO, "1", parent),
            "--manifest-path",
            str(self.root / "Cargo.toml"),
        ]

    def _run_id(self, result: subprocess.CompletedProcess[str]) -> str:
        matches: set[str] = set(RUN_ID_RE.findall(result.stdout + result.stderr))
        self.assertEqual(len(matches), 1, result.stdout + result.stderr)
        run_id = next(iter(matches))
        self.assertIsInstance(run_id, str)
        return run_id

    def _profile_files(self) -> dict[Path, bytes]:
        return {
            path.relative_to(self.cov_target): path.read_bytes()
            for path in self.cov_target.rglob("*.profraw")
        }

    def _profile_data_hashes(self) -> dict[Path, str]:
        return {
            path.relative_to(self.cov_target): hashlib.sha256(path.read_bytes()).hexdigest()
            for path in self.cov_target.rglob("*.profdata")
        }

    def _compiled_test_hashes(self) -> dict[Path, str]:
        dependencies = self.cov_target / "krr-coverage" / "deps"
        return {
            path.relative_to(self.cov_target): hashlib.sha256(path.read_bytes()).hexdigest()
            for path in dependencies.glob("native_nextest_retry_fixture-*")
            if path.is_file() and os.access(path, os.X_OK)
        }

    def _run_initial_failed_attempt(self) -> tuple[str, dict[str, object], dict[Path, bytes]]:
        first = self._run(self._nextest_arguments(None), "first")
        self.assertEqual(first.returncode, 100, first.stdout + first.stderr)
        run_id = self._run_id(first)
        self._assert_fixture_counts("1", "1")
        snapshot = retry_artifacts.snapshot(self.root, run_id)
        self.assertTrue(retry_artifacts.verify_snapshot(self.root, snapshot))
        profiles = self._profile_files()
        self.assertTrue(profiles, "initial test run did not retain LLVM profiles")
        return run_id, snapshot, profiles

    def _require_tools(self) -> None:
        for name, arguments in (
            ("llvm-cov-version", ["llvm-cov", "--version"]),
            ("nextest-version", ["nextest", "--version"]),
        ):
            result = self._execute(arguments, name, REPO, dict(os.environ))
            self.assertEqual(result.returncode, 0, result.stderr)

    def _assert_fixture_counts(self, passed: str, failed: str) -> None:
        self.assertEqual((self.state / "passed-count").read_text(), passed)
        self.assertEqual((self.state / "failed-count").read_text(), failed)

    def _coverage_report(self, stage: str) -> dict[str, object]:
        report_path = self.evidence / f"{stage}.json"
        result = self._run([
            "llvm-cov", "report", "--profile", "krr-coverage", "--locked",
            "--json", "--output-path", str(report_path),
        ], f"{stage}-command")
        self.assertEqual(result.returncode, 0, result.stderr)
        value = json.loads(report_path.read_text(encoding="utf-8"))
        if not isinstance(value, dict):
            self.fail("llvm-cov report is not a JSON object")
        return cast(dict[str, object], value)

    def _passed_only_function_count(self, report: dict[str, object]) -> int:
        data = report.get("data")
        if not isinstance(data, list):
            self.fail("llvm-cov export has no data array")
        source_path = str(self.root / "src/lib.rs")
        functions = self._reported_functions(data, source_path)
        self.assertEqual(len(functions), 1, functions)
        count = functions[0].get("count")
        self.assertIsInstance(count, int)
        if not isinstance(count, int):
            self.fail("passed-only function has no integer execution count")
        return count

    def _assert_report_contains_coverage(self) -> None:
        report = self._coverage_report("retained-coverage")
        self.assertGreater(self._passed_only_function_count(report), 0)

    def _reported_functions(self, data: list[object], source_path: str) -> list[dict[str, object]]:
        reported: list[dict[str, object]] = []
        for unit_value in data:
            if not isinstance(unit_value, dict):
                continue
            unit = cast(dict[str, object], unit_value)
            functions = unit.get("functions")
            if not isinstance(functions, list):
                continue
            reported.extend(self._matching_functions(functions, source_path))
        return reported

    def _matching_functions(
        self, functions: list[object], source_path: str,
    ) -> list[dict[str, object]]:
        matches: list[dict[str, object]] = []
        for function_value in functions:
            if not isinstance(function_value, dict):
                continue
            function = cast(dict[str, object], function_value)
            name, filenames = function.get("name"), function.get("filenames")
            if (isinstance(name, str) and "covered_only_by_passed_case" in name
                    and isinstance(filenames, list) and source_path in filenames):
                matches.append(function)
        return matches

    def test_full_uuid_retry_skips_passed_case_and_merges_retained_profiles(self) -> None:
        self._require_tools()
        lock_bytes = (self.root / "Cargo.lock").read_bytes()
        first_run_id, first_snapshot, first_profiles = self._run_initial_failed_attempt()

        retry = self._run(self._nextest_arguments(first_run_id), "retry")
        self.assertEqual(retry.returncode, 0, retry.stdout + retry.stderr)
        retry_run_id = self._run_id(retry)
        self.assertNotEqual(retry_run_id, first_run_id)
        self.assertFalse(retry_artifacts.verify_snapshot(self.root, first_snapshot))
        retry_snapshot = retry_artifacts.snapshot(self.root, retry_run_id)
        self.assertTrue(retry_artifacts.verify_snapshot(self.root, retry_snapshot))
        self._assert_fixture_counts("1", "2")
        retained_profiles = self._profile_files()
        self.assertTrue(set(first_profiles).issubset(retained_profiles))
        self.assertTrue(set(retained_profiles) - set(first_profiles))
        self.assertTrue(all(retained_profiles[path] == data for path, data in first_profiles.items()))
        self.assertEqual((self.root / "Cargo.lock").read_bytes(), lock_bytes)
        self._assert_report_contains_coverage()

    def test_profraw_only_clean_preserves_build_and_excludes_old_passed_coverage(self) -> None:
        self._require_tools()
        lock_bytes = (self.root / "Cargo.lock").read_bytes()
        first_run_id, _, first_profiles = self._run_initial_failed_attempt()
        first_report = self._coverage_report("before-profraw-clean")
        self.assertGreater(self._passed_only_function_count(first_report), 0)
        retained_profdata = self._profile_data_hashes()
        self.assertTrue(retained_profdata, "initial report did not retain LLVM profdata")
        compiled_artifacts = self._compiled_test_hashes()
        self.assertTrue(compiled_artifacts, "fixture test binary was not built")

        clean = self._run(coverage_commands.clean_arguments(), "profraw-only-clean")
        self.assertEqual(clean.returncode, 0, clean.stdout + clean.stderr)
        self.assertFalse(self._profile_files(), "profraw-only clean retained raw profiles")
        self.assertEqual(self._profile_data_hashes(), retained_profdata)
        self.assertEqual(self._compiled_test_hashes(), compiled_artifacts)

        retry = self._run(self._nextest_arguments(first_run_id), "retry-after-profraw-clean")
        self.assertEqual(retry.returncode, 0, retry.stdout + retry.stderr)
        retry_run_id = self._run_id(retry)
        self.assertNotEqual(retry_run_id, first_run_id)
        self._assert_fixture_counts("1", "2")
        new_profiles = self._profile_files()
        self.assertTrue(new_profiles, "failed-only retry did not write fresh profiles")
        self.assertTrue(set(first_profiles).isdisjoint(new_profiles))
        self.assertEqual(self._compiled_test_hashes(), compiled_artifacts)

        after_retry = self._coverage_report("after-profraw-clean-retry")
        self.assertEqual(self._passed_only_function_count(after_retry), 0)
        repeated = self._coverage_report("repeated-after-profraw-clean-retry")
        self.assertEqual(after_retry.get("data"), repeated.get("data"))
        self.assertEqual((self.root / "Cargo.lock").read_bytes(), lock_bytes)


if __name__ == "__main__":
    unittest.main()
