export async function auditRuntimeUnused(
  root: string,
  directory: string,
  inputs: OfficialStrictInputOptions = actualOfficialStrictInputs(),
) {
  const started = performance.now();
  const snapshot = runtimeUnusedContexts(root, inputs);
  const mathjaxProof = await inspectMathJaxStaticProof(root);
  const classicCapture = classicUnusedMetadata(
    root,
    snapshot.classicCaptureBindings,
    mathjaxProof.bundles,
    snapshot.contexts,
  );
  fs.writeFileSync(
    path.join(directory, "classic-capture-bindings.json"),
    JSON.stringify(classicCapture, null, 2),
  );
  const {
    bundle: checkedMathJax,
    module: mathjaxModule,
    rustFacts: mathjaxRustFacts,
  } = mathjaxProof;
  const staticMaterializerVerified = mathjaxRustFacts.facts.some(
    (fact) => fact.id === "default-materializer",
  );
  const defaultStaticClosed = mathjaxProof.defaultStaticClosed;
  const mathjaxStatic = {
    auditOnly: true,
    staticMaterializerVerified,
    defaultStaticClosed,
    generatedContentSha256: createHash("sha256")
      .update(Buffer.from(checkedMathJax.content, "utf8"))
      .digest("hex"),
    checkedBundleChecksum: checkedMathJax.checksum,
    rustGeneratedContentSha256: mathjaxRustFacts.inputSha256[MATHJAX_GENERATED_OUTPUT_PATH] ?? null,
    acceptedConsumerClosure: false,
    generatedGlobalVerified: false,
    canonicalInspectionGlobalVerified: mathjaxModule.canonicalInspectionGlobalVerified,
    externalOverrideVerified: false,
    nativeRuntimeVerified: false,
    rustFacts: {
      schema: mathjaxRustFacts.schema,
      status: mathjaxRustFacts.status,
      parser: mathjaxRustFacts.parser,
      factCount: mathjaxRustFacts.facts.length,
      inputPinCount: Object.keys(mathjaxRustFacts.inputSha256).length,
      staticMaterializerVerified,
      generatedGlobalVerified: mathjaxRustFacts.generatedGlobalVerified,
      overrideContentVerified: mathjaxRustFacts.overrideContentVerified,
      facts: mathjaxRustFacts.facts,
      inputSha256: mathjaxRustFacts.inputSha256,
    },
    generatedBundle: {
      outputFile: checkedMathJax.definition.outputFile,
      outputPath: checkedMathJax.outputPath,
      contentSha256: createHash("sha256").update(checkedMathJax.content).digest("hex"),
      checksum: checkedMathJax.checksum,
      contentLength: checkedMathJax.content.length,
    },
  } as const;
  const config = artifactConfiguration(root, directory);
  let peakObservedRss = process.memoryUsage().rss;
  const reports = [];
  for (const context of snapshot.contexts) {
    if (context.programs && "map" in context.origin) {
      fs.writeFileSync(path.join(directory, `${context.name}.map.json`), context.origin.map);
      fs.writeFileSync(
        path.join(directory, `${context.name}.programs.json`),
        JSON.stringify(
          unusedProgramMetadata(context.name, context.programs, context.externalInputs),
          null,
          2,
        ),
      );
    }
    for (const stage of context.stages) {
      const code =
        stage === "assembled" ? context.origin.assembled : context.origin.provenance.code;
      const result = contextDiagnostics(root, directory, config, `${context.name}.${stage}`, code);
      verifyContextExternalInputs(context);
      const diagnostics = result.diagnostics.map((diagnostic) => {
        try {
          return { diagnostic, origin: context.origin.resolve(diagnostic, stage), unknown: null };
        } catch (error) {
          return { diagnostic, origin: null, unknown: String(error) };
        }
      });
      const coverage = context.origin.coverage(stage);
      reports.push({
        name: context.name,
        stage,
        codeBytesEqual: context.codeBytesEqual,
        programs: context.programs ?? null,
        externalInputs: context.externalInputs ?? null,
        projectionOnly: context.programs !== undefined,
        ...result,
        diagnostics,
        coverage,
      });
      peakObservedRss = Math.max(peakObservedRss, process.memoryUsage().rss);
    }
  }
  verifyUnusedSources(root, snapshot.raw);
  const mathjaxOwnedRaw: MathJaxOwnedRawReport = await auditMathJaxOwnedSource(
    root,
    directory,
    (name, code) => contextDiagnostics(root, directory, config, name, code),
  );
  snapshot.contexts.forEach(verifyContextExternalInputs);
  verifyClassicUnusedBindings(snapshot.classicCaptureBindings);
  return {
    schema: 1,
    auditOnly: true,
    rawUnusedRouteChanged: false,
    standardRegistration: "pending-root",
    scopeComplete: false,
    incompleteConsumers: incompleteUnusedConsumerReport(mathjaxStatic.defaultStaticClosed),
    moduleEntry: snapshot.moduleEntry,
    rawSourceCount: snapshot.raw.size,
    contexts: reports,
    classicCapture,
    mathjaxOwnedRaw,
    mathjaxStatic,
    elapsedMs: performance.now() - started,
    peakObservedRss,
    // 現phaseのconsumer未閉包を空診断で合格へすり替えない。
    accepted: false,
  };
}

