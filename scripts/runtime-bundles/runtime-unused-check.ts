function unusedGateDirectory(root: string, directory: string) {
  if (
    fs.realpathSync(root) !== root ||
    !path.isAbsolute(directory) ||
    path.resolve(directory) !== directory ||
    !directory.startsWith(`${root}${path.sep}tmp${path.sep}`)
  )
    throw new Error("unused gate directory/root mismatch");
  let current = root;
  for (const part of path.relative(root, directory).split(path.sep)) {
    current = path.join(current, part);
    if (!fs.existsSync(current)) fs.mkdirSync(current);
    if (
      fs.lstatSync(current).isSymbolicLink() ||
      !fs.lstatSync(current).isDirectory() ||
      fs.realpathSync(current) !== current
    )
      throw new Error("unused gate evidence symlink/non-directory");
  }
}

function standardBiomeToolPin(lookupPath: string) {
  const physicalPath = canonicalRegularFile(fs.realpathSync(lookupPath), "standard Biome tool");
  return {
    lookupPath,
    physicalPath,
    symlink: fs.lstatSync(lookupPath).isSymbolicLink() ? fs.readlinkSync(lookupPath) : null,
    sha256: digest(fs.readFileSync(physicalPath)),
    size: fs.statSync(physicalPath).size,
  };
}

function standardBiomeNativePackage(platform: string, arch: string) {
  if (!["darwin", "linux", "win32"].includes(platform) || !["arm64", "x64"].includes(arch))
    throw new Error("unknown standard Biome platform");
  let musl = false;
  if (platform === "linux") {
    let output: Buffer;
    try {
      output = execFileSync("ldd", ["--version"], { stdio: ["pipe", "pipe", "pipe"] });
    } catch (error) {
      output = z.object({ stderr: z.instanceof(Buffer) }).parse(error).stderr;
    }
    musl = output.includes("musl");
  }
  return `@biomejs/cli-${platform}-${arch}${musl ? "-musl" : ""}`;
}

