function isMathJaxDefaultStaticClosed(
  root: string,
  bundle: GeneratedBundle,
  module: MathJaxModuleOrigin,
  rustFacts: MathJaxRustStaticFacts,
): boolean {
  let validatedFacts: MathJaxRustStaticFacts;
  try {
    validatedFacts = validateMathJaxRustFacts(root, rustFacts);
  } catch {
    return false;
  }

  const generatedContentSha256 = createHash("sha256")
    .update(Buffer.from(bundle.content, "utf8"))
    .digest("hex");
  const rustGeneratedContentSha256 = validatedFacts.inputSha256[MATHJAX_GENERATED_OUTPUT_PATH];
  const canonicalDefinition =
    bundle.definition.name === "mathjax" &&
    bundle.definition.outputFile === "mathjax-runtime.min.js" &&
    bundle.definition.fragments.length === 0 &&
    bundle.definition.bundledEntryPath === MATHJAX_SOURCE_PATH &&
    path.resolve(bundle.outputPath) === path.resolve(root, MATHJAX_GENERATED_OUTPUT_PATH);
  const canonicalModuleGraph =
    module.acceptedConsumerClosure === false &&
    module.auditOnly === true &&
    module.input === MATHJAX_MODULE_ENTRY &&
    module.moduleCount === 220 &&
    module.staticImportCount === MATHJAX_STATIC_IMPORTS.length &&
    module.sourceMapSourceCount === 219 &&
    module.physicalSources.length === 219 &&
    module.externalNodeCount === 0 &&
    module.dynamicNodeCount === 0 &&
    module.canonicalInspectionGlobalVerified;
  const canonicalRustFacts =
    validatedFacts.status === "verified" &&
    validatedFacts.facts.length === 13 &&
    validatedFacts.facts.some((fact) => fact.id === "default-materializer");

  return (
    canonicalDefinition &&
    canonicalModuleGraph &&
    canonicalRustFacts &&
    generatedContentSha256 === bundle.checksum &&
    generatedContentSha256 === rustGeneratedContentSha256
  );
}

function incompleteUnusedConsumerReport(mathjaxDefaultStaticClosed: boolean): string[] {
  return mathjaxDefaultStaticClosed
    ? [...incompleteUnusedConsumers]
    : [...incompleteUnusedConsumers, MATHJAX_INCOMPLETE_CONSUMER];
}

interface MathJaxStaticProof {
  bundles: readonly GeneratedBundle[];
  bundle: GeneratedBundle;
  module: MathJaxModuleOrigin;
  rustFacts: MathJaxRustStaticFacts;
  defaultStaticClosed: boolean;
}

async function inspectMathJaxStaticProof(root: string): Promise<MathJaxStaticProof> {
  const checkedBundles = await new RuntimeBundleCommand(root, "check").generateCheckedBundles();
  const bundle = checkedBundles.find((candidate) => candidate.definition.name === "mathjax");
  if (!bundle) throw new Error("checked MathJax bundle is missing");
  const module = await inspectMathJaxModule(root);
  const rustFacts = inspectMathJaxRustFacts(root);
  return {
    bundles: checkedBundles,
    bundle,
    module,
    rustFacts,
    defaultStaticClosed: isMathJaxDefaultStaticClosed(root, bundle, module, rustFacts),
  };
}

