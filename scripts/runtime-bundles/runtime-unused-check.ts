function officialStrictProgramMetadata(
  programs: readonly BrowserUnusedProgram[],
  externalInputs: readonly OfficialStrictExternalInput[] | undefined,
) {
  programs.forEach((program) => {
    officialStrictProgramSchema.parse(program);
  });
  const expectedSources = [
    officialStrictConsumerRoute[0].sourcePath,
    officialStrictConsumerRoute[2].sourcePath,
    officialStrictConsumerRoute[2].sourcePath,
    officialStrictConsumerRoute[4].sourcePath,
    officialStrictConsumerRoute[4].sourcePath,
  ];
  if (
    (programs[1]?.start ?? Infinity) >= (programs[2]?.start ?? -1) ||
    (programs[3]?.start ?? Infinity) >= (programs[4]?.start ?? -1)
  )
    throw new Error("wrong official strict callback manifest order");
  if (
    programs.map((program) => program.sourcePath).join("/") !== expectedSources.join("/") ||
    programs.some(
      (program) =>
        program.role !== "callback" ||
        program.mode !== "strictVendorOriginal" ||
        (program.consumerRoute ?? []).map((binding) => binding.sourcePath).join("/") !==
          officialStrictConsumerRoute.map((binding) => binding.sourcePath).join("/"),
    ) ||
    programs.some(
      (program) =>
        JSON.stringify(program.consumerRoute) !== JSON.stringify(programs[0]?.consumerRoute),
    ) ||
    !externalInputs
  )
    throw new Error("wrong official strict browser realm programs/inputs");
  verifyOfficialStrictExternalInputs(externalInputs);
  return {
    realm: "official Mermaid strict page; shared capture/image helpers",
    projectionOnly: true,
    staticInputCandidate: true,
    acceptedConsumerClosure: false,
    externalRuntimeConfigObserved: false,
    nativeRuntimeVerified: false,
    browserExecutionVerified: false,
    executionVerified: false,
    artifactVerified: false,
    fullSourceClosure: false,
    programOrder:
      "renderVendorOriginalSvg; assignStrictSvg; observeCaptureSnapshot; href collection; image load/decode",
    sharedSizingContext: "shared-svg-capture-sizing (one resizeSvgCapture callback, reused)",
    externalProgramsUnmapped: [
      "selected Mermaid/ZenUML implementation bytes; browser loading/execution",
    ],
    externalInputs,
    programs,
  };
}

export function unusedProgramMetadata(
  name: string,
  programs: readonly BrowserUnusedProgram[],
  externalInputs?: readonly OfficialStrictExternalInput[],
) {
  if (name === "official-mermaid-strict-browser")
    return officialStrictProgramMetadata(programs, externalInputs);
  if (name === "official-mermaid-browser") {
    if (
      programs.some(
        (program) =>
          !["provider", "callback"].includes(program.role) ||
          ["rust-native-test", "node-function-test", "shared-svg-capture"].includes(program.mode),
      )
    )
      throw new Error("wrong official browser realm programs");
    return {
      realm: "official Mermaid nonstrict page",
      projectionOnly: true,
      programOrder: "provider order; callback inventory is not an execution schedule",
      externalProgramsUnmapped: ["options.mermaidJs", "options.mermaidZenumlJs"],
      programs,
    };
  }
  if (name === "shared-svg-capture-sizing") {
    if (
      programs.length !== 1 ||
      programs[0]?.role !== "callback" ||
      programs[0]?.mode !== "shared-svg-capture"
    )
      throw new Error("wrong shared SVG sizing realm programs");
    return {
      realm: "shared SVG sizing page.evaluate callback; officialFallback and strictViewBox callers",
      projectionOnly: true,
      executionVerified: false,
      artifactVerified: false,
      fullSourceClosure: false,
      programOrder: "one actual callback; both actual serialized strict/mode caller paths bound",
      externalProgramsUnmapped: ["other browser programs and sizing execution/timing"],
      programs,
    };
  }
  if (name === "node-function-static-load-test") {
    if (
      programs.map((program) => program.role).join("/") !==
        "node-function-parameters/node-function-body/node-function-body/node-function-return" ||
      programs.some((program) => program.mode !== "node-function-test")
    )
      throw new Error("wrong node Function realm programs");
    return {
      realm: "Node/Bun unit new Function, installStaticLoadHandler constructor",
      projectionOnly: true,
      programOrder: "actual parameters; two regex-selected handlers; actual return",
      executionVerified: false,
      artifactVerified: false,
      fullSourceClosure: false,
      externalProgramsUnmapped: [
        "other dom_bootstrap.js spans and constructors",
        "native HTML bootstrap consumer",
      ],
      programs,
    };
  }
  return nativeWidthProgramMetadata(name, programs);
}

function nativeWidthProgramMetadata(name: string, programs: readonly BrowserUnusedProgram[]) {
  if (!isNativeWidthProgramSet(name, programs)) throw new Error("unknown unused program realm");
  return {
    realm: "Rust native-width test, shared V8 classic-script context",
    projectionOnly: true,
    programOrder:
      "trace before render entrypoint; actual result literal appended after runtime scripts",
    externalProgramsUnmapped: [
      "RuntimeAsset::mermaid materialized bundle",
      "other MermaidRuntimeScripts::build scripts",
    ],
    executionVerified: false,
    artifactVerified: false,
    programs,
  };
}

function isNativeWidthProgramSet(name: string, programs: readonly BrowserUnusedProgram[]) {
  const roles = ["native-test-trace", "native-test-trace", "rust-result-literal"] as const;
  const route = programs[0]?.consumerRoute;
  const routeByPath = new Map(
    route?.map((binding) => [binding.sourcePath, binding.sourceSha256] as const),
  );
  return (
    name === "rust-native-width-test-result" &&
    programs.length === NATIVE_WIDTH_PROGRAM_PATHS.length &&
    !programs.some(
      (program, index) =>
        program.sourcePath !== NATIVE_WIDTH_PROGRAM_PATHS[index] ||
        program.role !== roles[index] ||
        program.mode !== "rust-native-test" ||
        routeByPath.get(program.sourcePath) !== program.sourceSha256 ||
        JSON.stringify(program.consumerRoute) !== JSON.stringify(route),
    ) &&
    routeByPath.size === route?.length
  );
}

