import { beforeAll, describe, expect, test } from "bun:test";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { createContext, runInContext } from "node:vm";
import {
  checkParserBodyOnload,
  checkParserBodyOnloadFiles,
  generateParserBodyOnload,
  parserBodyOnloadDirectory,
} from "./parser-body-onload-generation";

const root = path.resolve(import.meta.dir, "../..");
const directory = path.join(root, parserBodyOnloadDirectory);
const original = fs.readFileSync(path.join(directory, "parser_body_onload.js"), "utf8");
let generated = "";

beforeAll(() => {
  generated = generateParserBodyOnload(
    fs.readFileSync(path.join(directory, "parser_body_onload.ts"), "utf8"),
    root,
  );
});

interface ParserFixtureOptions {
  body?: string | null;
  frameset?: string | null;
  source?: string | null;
  queryError?: boolean;
  attributeError?: boolean;
}

function parserFixture(options: ParserFixtureOptions = {}) {
  const target = {};
  const elements = new Map<string, { readonly __krrNodeId: string }>();
  const handlers = new WeakMap<object, Map<string, (event: unknown) => unknown>>();
  const overrides = new WeakMap<object, Set<string>>();
  const attributes = new Map<string, string>();
  const calls: { operation: string; args: unknown[] }[] = [];
  const elementCalls: (string | null | undefined)[] = [];
  const bodyId = options.body === undefined ? "17" : options.body;
  const framesetId = options.frameset ?? null;
  for (const id of [bodyId, framesetId]) {
    if (id !== null && options.source !== null && options.source !== undefined) {
      attributes.set(id, options.source);
    }
  }
  const querySelector = (selector: unknown): string | null | undefined => {
    if (options.queryError) return undefined;
    if (selector === "body") return bodyId;
    if (selector === "html > frameset") return framesetId;
    throw new Error("Unexpected unit selector");
  };
  const getAttribute = (id: unknown, name: unknown): string | null | undefined => {
    if (options.attributeError || id === undefined) return undefined;
    if (typeof id !== "string" || name !== "onload") throw new Error("Invalid unit attribute");
    return attributes.get(id) ?? null;
  };
  const setAttribute = (id: unknown, name: unknown, value: unknown): undefined => {
    if (typeof id !== "string" || name !== "onload" || typeof value !== "string") {
      throw new Error("Invalid unit mutation");
    }
    attributes.set(id, value);
    return undefined;
  };
  const nativeDom = (operation: string, ...args: unknown[]): string | null | undefined => {
    calls.push({ operation, args });
    switch (operation) {
      case "querySelector":
        return querySelector(args[0]);
      case "getAttribute":
        return getAttribute(args[0], args[1]);
      case "setAttribute":
        return setAttribute(args[0], args[1], args[2]);
      default:
        throw new Error("Unexpected unit nativeDom operation");
    }
  };
  const element = (id: string | null | undefined) => {
    elementCalls.push(id);
    if (id === null || id === undefined) return null;
    const value = { __krrNodeId: id };
    elements.set(id, value);
    return value;
  };
  const context = createContext({
    window: target,
    __krrNativeDom: nativeDom,
    __krrElement: element,
    __krrElements: elements,
    __krrEventHandlers: handlers,
    __krrLifecyclePropertyOverrides: overrides,
  });
  const pageGlobal: unknown = runInContext("globalThis", context);
  if (typeof pageGlobal !== "object" || pageGlobal === null) throw new Error("Missing VM global");
  const loadOverrides = new Set(["load"]);
  overrides.set(pageGlobal, loadOverrides);
  const installer: unknown = runInContext(generated, context);
  if (typeof installer !== "function") throw new Error("Parser result must be a Function");
  return {
    install: (source: string | undefined, later: boolean): unknown =>
      Reflect.apply(installer, undefined, [source, later]),
    handler: () => handlers.get(target)?.get("load"),
    calls,
    elementCalls,
    elements,
    attributes,
    loadOverrides,
    context,
  };
}

describe("parser body-onload generated bytes (pure unit)", () => {
  test("canonical TS produces the frozen runtime without comments or wrappers", () => {
    expect(generated).toBe(original);
    expect(Buffer.byteLength(generated)).toBe(2138);
    expect(createHash("sha256").update(generated).digest("hex")).toBe(
      "d022225726d219c9fdbdc144e463b3edae41f91daf7b918cf27dcc186386e0d4",
    );
    expect(() => checkParserBodyOnloadFiles(root)).not.toThrow();
  });

  test("exact-byte check rejects whitespace, comments and changed execution", () => {
    for (const changed of [
      `${original}\n`,
      `// extra\n${original}`,
      original.replace('"load"', '"other"'),
    ]) {
      expect(() => checkParserBodyOnload(generated, changed)).toThrow("runtime is stale");
    }
  });
});

describe("parser body-onload standard VM (pure unit, not native acceptance)", () => {
  test("evaluation returns callable installer and passes receiver/event through registry", () => {
    const fixture = parserFixture();
    const source = "return [this.__krrNodeId, event];";
    expect(fixture.install(source, false)).toBeUndefined();
    expect(fixture.attributes.get("17")).toBe(source);
    expect(fixture.loadOverrides.has("load")).toBe(false);
    expect(fixture.handler()?.("event-value")).toEqual(["17", "event-value"]);
    expect(fixture.elementCalls).toEqual(["17"]);
    expect(fixture.calls).toEqual([
      { operation: "querySelector", args: ["body"] },
      { operation: "querySelector", args: ["body"] },
      { operation: "getAttribute", args: ["17", "onload"] },
      { operation: "setAttribute", args: ["17", "onload", source] },
    ]);
  });

  test("body/frameset precedence and no-node path preserve string IDs", () => {
    for (const [body, frameset, id] of [
      ["17", "29", "17"],
      [null, "29", "29"],
      [null, null, null],
    ]) {
      if (
        (typeof body !== "string" && body !== null) ||
        (typeof frameset !== "string" && frameset !== null) ||
        (typeof id !== "string" && id !== null)
      )
        throw new Error("Invalid unit row");
      const fixture = parserFixture({ body, frameset });
      fixture.install("return this.__krrNodeId;", false);
      if (id === null) {
        expect(fixture.handler()).toBeUndefined();
        expect(fixture.calls.every((call) => call.operation === "querySelector")).toBe(true);
      } else {
        expect(fixture.handler()?.(undefined)).toBe(id);
        expect(fixture.attributes.has(id)).toBe(true);
      }
    }
  });

  test("undefined source uses current attribute and null source clears handlers", () => {
    const fixture = parserFixture({ source: "return event;" });
    fixture.install(undefined, false);
    const event = {};
    expect(fixture.handler()?.(event)).toBe(event);
    fixture.attributes.delete("17");
    fixture.install(undefined, false);
    expect(fixture.handler()).toBeUndefined();
  });

  test("later unequal/equal attribute preserves handler and initial equal installs", () => {
    const fixture = parserFixture({ source: "return 1;" });
    fixture.install("return 1;", true);
    expect(fixture.handler()).toBeUndefined();
    fixture.install("return 2;", false);
    expect(fixture.handler()).toBeUndefined();
    fixture.install("return 1;", false);
    expect(fixture.handler()?.(undefined)).toBe(1);
    const handler = fixture.handler();
    fixture.install("return 2;", true);
    expect(fixture.handler()).toBe(handler);
    expect(fixture.calls.some((call) => call.operation === "setAttribute")).toBe(false);
  });

  test("invalid author code clears registry and captured overrides", () => {
    const fixture = parserFixture();
    fixture.install("invalid {", false);
    expect(fixture.handler()).toBeUndefined();
    expect(fixture.loadOverrides.has("load")).toBe(false);
  });

  test("native undefined failures remain distinct from successful setAttribute undefined", () => {
    for (const options of [{ queryError: true }, { attributeError: true }]) {
      const fixture = parserFixture(options);
      expect(fixture.install(undefined, false)).toBeUndefined();
      expect(fixture.handler()).toBeUndefined();
      expect(fixture.calls.some((call) => call.operation === "setAttribute")).toBe(false);
      if (options.queryError) {
        expect(fixture.elementCalls).toEqual([undefined, undefined]);
        expect(fixture.calls.find((call) => call.operation === "getAttribute")?.args).toEqual([
          undefined,
          "onload",
        ]);
      }
    }
  });

  test("captured uncurried methods survive page prototype redefinition", () => {
    // 改変された VM 内 Map の検査にも、外側の組み込み method を使う。
    const script = `
      const vm = require("node:vm");
      const fs = require("node:fs");
      const handlers = new WeakMap();
      const overrides = new WeakMap();
      const target = {};
      let attribute = null;
      const context = vm.createContext({
        window: target,
        __krrElements: new Map(),
        __krrEventHandlers: handlers,
        __krrLifecyclePropertyOverrides: overrides,
        __krrElement: id => ({ __krrNodeId: id }),
        __krrNativeDom: (op, id, name, value) => {
          if (op === "querySelector") return "17";
          if (op === "getAttribute") return attribute;
          if (op === "setAttribute") { attribute = value; return undefined; }
          throw Error("Unexpected unit op");
        },
      });
      const removed = new Set(["load"]);
      overrides.set(vm.runInContext("globalThis", context), removed);
      const installer = vm.runInContext(fs.readFileSync(0, "utf8"), context);
      if (typeof installer !== "function") throw Error("Missing installer");
      vm.runInContext('for (const [p, names] of [[WeakMap.prototype, ["get", "set"]], [Map.prototype, ["get", "set", "delete"]], [Set.prototype, ["delete"]]]) for (const n of names) p[n] = () => { throw Error("page override"); };', context);
      installer("return event;", false);
      if (Map.prototype.get.call(handlers.get(target), "load")("kept") !== "kept" || removed.has("load")) throw Error("Capture failed");
      attribute = null;
      installer(undefined, false);
      if (Map.prototype.has.call(handlers.get(target), "load")) throw Error("Captured delete failed");
      process.stdout.write("captured intrinsics preserved");
    `;
    const result = spawnSync("node", ["-e", script], { input: generated, encoding: "utf8" });
    if (result.error) throw result.error;
    expect(result.status).toBe(0);
    expect(result.stderr).toBe("");
    expect(result.stdout).toBe("captured intrinsics preserved");
  });
});

describe("native parser ABI type boundaries (compiler-only unit)", () => {
  test("valid wire calls compile while wrong op/NodeId/arguments/DOM references fail", () => {
    const temporary = fs.mkdtempSync(path.join(os.tmpdir(), "krr-parser-types-"));
    try {
      fs.copyFileSync(
        path.join(directory, "host_parser_onload.d.ts"),
        path.join(temporary, "host.d.ts"),
      );
      fs.writeFileSync(
        path.join(temporary, "tsconfig.json"),
        JSON.stringify({
          compilerOptions: {
            target: "ES2024",
            lib: ["ES2024"],
            types: [],
            strict: true,
            noEmit: true,
          },
          files: ["host.d.ts", "input.ts"],
        }),
      );
      const cases = [
        {
          code: '__krrNativeDom("querySelector", "body"); __krrNativeDom("getAttribute", undefined, "onload"); __krrNativeDom("setAttribute", "17", "onload", "");',
          valid: true,
        },
        { code: '__krrNativeDom("removeChild", "17");', valid: false },
        { code: '__krrNativeDom("getAttribute", 17, "onload");', valid: false },
        { code: '__krrNativeDom("getAttribute", 17n, "onload");', valid: false },
        { code: '__krrNativeDom("setAttribute", "17", "onload", undefined);', valid: false },
        { code: 'const id: string = __krrNativeDom("querySelector", "body");', valid: false },
        { code: "document.body; const node: HTMLElement = window;", valid: false },
      ];
      for (const sample of cases) {
        fs.writeFileSync(path.join(temporary, "input.ts"), sample.code);
        const result = spawnSync(
          "bunx",
          ["--no-install", "tsc", "--noEmit", "-p", path.join(temporary, "tsconfig.json")],
          { cwd: root, encoding: "utf8" },
        );
        if (result.error) throw result.error;
        expect(result.status === 0).toBe(sample.valid);
        if (!sample.valid) expect(result.stdout).toContain("error TS");
      }
    } finally {
      fs.rmSync(temporary, { recursive: true, force: true });
    }
  });
});
